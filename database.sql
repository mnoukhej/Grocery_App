-- 1. Units of Measurement Table ---------------------
CREATE TABLE IF NOT EXISTS `gs`.`uom` (
  `uom_id` INT NOT NULL AUTO_INCREMENT,
  `uom_name` VARCHAR(45) NOT NULL,
  PRIMARY KEY (`uom_id`)
);

